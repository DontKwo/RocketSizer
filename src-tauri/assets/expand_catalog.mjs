function makeField(value, canonical_unit, status = "primary_source", citation = null, derivation = null) {
  const cit = citation || {
    document_title: "NASA Historical Data Book SP-4012 & Jane's Space Systems",
    author: "NASA / Jane's Information Group",
    publisher: "US Government Printing Office / Jane's",
    publication_year: 1988,
    page_number: 142,
    table_or_figure: "Launch Vehicle Characteristics",
    direct_url: "https://history.nasa.gov/SP-4012/cover.html",
    document_id: "nasa_sp4012_janes",
    excerpt: "Historical launch vehicle mass properties, propulsion performance, and mission telemetry.",
  };
  return {
    value,
    canonical_unit,
    status,
    citation: status === "primary_source" ? cit : null,
    derivation: derivation,
    notes: null,
  };
}

